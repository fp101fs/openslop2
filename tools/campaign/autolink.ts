// Usage: bun tools/campaign/autolink.ts [nco|wol]
// For each mission, bridges every walkable region that holds a mission point / enemy base to the start's region with a ramp op,
// appending to src/campaign/maps/links.ts (data; delete entries to undo). Re-run mapcheck afterwards.
import { CAMPAIGNS } from '../../src/campaign/registry';
import { analyze } from './mapLib';
import { writeFileSync } from 'fs';
import { LINKS, PADS } from '../../src/campaign/maps/links';
const only = process.argv[2];
const out: Record<string, any[]> = JSON.parse(JSON.stringify(LINKS));
const pads: Record<string, any[]> = JSON.parse(JSON.stringify(PADS));
for (const c of CAMPAIGNS) {
  if (only && c.id !== only) continue;
  for (const m of c.missions) {
    const extra: any[] = (out[m.mapId] ?? []).map(([a, b, w, t0, t1]) => ({ op: 'ramp', a, b, width: w, t0, t1 }));
    // clearings for points (and resources) that sit inside rock
    {
      const A0 = analyze(c.id, m, [...(pads[m.mapId] ?? []).map(([x, y, t, rad]) => ({ op: 'tier', shape: { k: 'ell', x, y, rx: rad, ry: rad }, tier: t, wob: 0.4 })), ...extra]);
      if (A0) {
        const seenP = new Set<string>(); const need: [number, number, number][] = [];
        for (const [x, y] of A0.pts) if (A0.snap(x, y) < 0) need.push([x, y, 5]);
        for (const b of A0.def.bases) for (const p of [...b.minerals, ...b.geysers] as [number, number][]) if (A0.r.blocked[A0.cell(p[0], p[1])]) need.push([p[0], p[1], 3]);
        for (const [x, y, rad] of need) {
          const k = `${Math.round(x)},${Math.round(y)}`; if (seenP.has(k)) continue; seenP.add(k);
          let tier = 0, found = false;
          for (let d = 1; d <= 40 && !found; d++) for (let a = 0; a < 360 && !found; a += 15) { const px = x + Math.cos(a * Math.PI / 180) * d, py = y + Math.sin(a * Math.PI / 180) * d; if (A0.ok(px, py)) { tier = Math.round(A0.r.tier[A0.cell(px, py)]!); found = true; } }
          (pads[m.mapId] ??= []).push([Math.round(x * 2) / 2, Math.round(y * 2) / 2, tier, rad]);
          console.log(`${c.id}/${m.key}: clearing at ${x},${y} r${rad} tier ${tier}`);
        }
      }
    }
    const padOps = (pads[m.mapId] ?? []).map(([x, y, t, rad]) => ({ op: 'tier', shape: { k: 'ell', x, y, rx: rad, ry: rad }, tier: t, wob: 0.4 }));
    for (let iter = 0; iter < 12; iter++) {
      const A = analyze(c.id, m, [...padOps, ...extra]); if (!A) break;
      const { def, r, comp, size, snap, start } = A, res = r.res;
      const sc = snap(start[0], start[1]); if (sc < 0) break;
      const need = new Set<number>();
      const targets = [...A.pts, ...def.bases.map((b: any) => b.th as [number, number])];
      for (const [x, y] of targets) { const k = snap(x, y); if (k >= 0 && k !== sc) need.add(k); }
      if (!need.size) break;
      // nearest unlinked region to the start region
      const mainCells: number[] = [], pick = (k: number, st = 3) => { const a: number[] = []; for (let i = 0; i < comp.length; i += st) if (comp[i] === k) a.push(i); return a; };
      mainCells.push(...pick(sc, 17));
      let best: any = null;
      for (const k of need) {
        for (const i of pick(k, 5)) {
          const ax = (i % res) / 2, ay = ((i / res) | 0) / 2;
          for (const j of mainCells) { const bx = (j % res) / 2, by = ((j / res) | 0) / 2; const d = Math.hypot(ax - bx, ay - by); if (!best || d < best.d) best = { d, a: [ax, ay], b: [bx, by], i, j }; }
        }
      }
      if (!best) break;
      const t0 = Math.round(r.tier[best.i]!), t1 = Math.round(r.tier[best.j]!);
      const link = [best.a, best.b, 6, t0, t1];
      (out[m.mapId] ??= []).push(link); extra.push({ op: 'ramp', a: best.a, b: best.b, width: 6, t0, t1 });
      console.log(`${c.id}/${m.key}: link ${JSON.stringify(best.a)} -> ${JSON.stringify(best.b)} (${best.d.toFixed(1)} tiles)`);
    }
  }
}
const fmt = (o: Record<string, any[]>) => Object.entries(o).map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`).join(',\n');
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`).join(',\n');
writeFileSync('src/campaign/maps/links.ts', `import type { Pt } from '../../levels/LevelTypes';\n\n/** Auto-generated by tools/campaign/autolink.ts: [a, b, width, tierFrom, tierTo] ramps that connect cut-off regions. Delete an entry to undo it; maps/builder.ts merges these. */\nexport const LINKS: Record<string, [Pt, Pt, number, number, number][]> = {\n${body}\n};\n\n/** Clearings carved into rock around objective points: [x, y, tier, radius]. Same tool, same rules. */\nexport const PADS: Record<string, [number, number, number, number][]> = {\n${fmt(pads)}\n};\n`);
