#!/usr/bin/env python3
"""Regenerate src/credits/modelCredits.json: author / licence / source of every .glb under public/ (read from the Sketchfab metadata
embedded in each file), grouped per source model. Files whose metadata was lost in the build pipeline (tools/model/build-static.ts,
texture-depot.py) are filled in from OVERRIDES (the original download's metadata).   python3 tools/model/credits.py"""
import struct, json, glob, os, re, subprocess

def meta(path):
    raw = open(path, 'rb').read(); l, _ = struct.unpack('<II', raw[12:20])
    a = json.loads(raw[20:20 + l]).get('asset', {}); ex = a.get('extras') or {}
    return ex

def sk(title, author, handle, slug, lic='CC-BY-4.0'):
    return {'title': title, 'author': author, 'authorUrl': f'https://sketchfab.com/{handle}', 'license': lic, 'source': f'https://sketchfab.com/3d-models/{slug}'}

OVERRIDES = {
    'models/firebat.glb': sk('AEGIS Firebat - Free Terran Heavy Armor', 'AEGISPROJECT', 'AEGISPROJECT', 'aegis-firebat-free-terran-heavy-armor-9e0bfa3341ea4328892f1c1bafbbedf9'),
    'models/drone.glb': sk('Drone Starcraft Zerg Untextured', 'woodsquid', 'woodsquid', 'drone-starcraft-zerg-untextured-b2eb372d658844a99c0130cb87f4ba17'),
    'models/medic.glb': sk('Medibat (modified CMC-405)', 'Csaba Baity (tsabszy)', 'tsabszy', 'medibat-modified-cmc-405-2163d9a2555e480d87e01fc4baf2d28a'),
    'models/ghost.glb': sk('Combine Soldier', 'MrYoink', 'mryoinkie', 'combine-soldier-6fa87ed8061b4bda85cd5b4b8bd7b7b2', 'CC-BY-4.0'),
    # recoloured by tools/model/build-overlord.ts (the build drops the embedded metadata)
    'models/overlord.glb': sk('Overlord Zerg Starcraft Uncolored (decimated, recoloured)', 'woodsquid', 'woodsquid', 'overlord-zerg-starcraft-uncolored-8ce546e99b254da980fd23fe1670daad'),
    'models/swarm_host.glb': sk('Starcraft 2 Swarm Host (decimated, recoloured)', 'George Prior', 'georgeprior321', 'starcraft-2-swarm-host-63ead5ff63ac4c53a7e48707c3dc5173'),
    'models/refinery.glb': sk('Sci-Fi Gas Vents Resource', 'np-dev', 'np-dev', 'sci-fi-gas-vents-resource-3e9021811efb4a3998bfa84405eb4332'),
    # baked by tools/bakeLiquidMelt.ts (decimated flipbook, played in reverse; the bake drops the embedded metadata)
    'models/fx/liquid_melt.glb': sk('T1000 Liquid Metal (decimated, reversed)', 'designidentity', 'designidentity', 't1000-liquid-metal-a2e0303ccfe24802b289b7196b789699'),
}
# Non-GLB files cut from a downloaded model (always used by the game code).
EXTRA = {
    'textures/zerg_blood_web.webp': sk('blood eye (texture crop, mirror-tiled)', 'Pakawat', 'Pakawat', 'blood-eye-8a16b4071fd74f96af1d633f52b82dfa'),
}
# The Supply Depot models and the models made in this project have no embedded author metadata.
OWN_WORK = {'models/supply_depot_animated.glb', 'models/supply_depot_lowered.glb', 'models/supply_depot_normal.glb',
            # models made in this project (see docs/SC2-PARITY.md, 'Models we made')
            'models/armory.glb', 'models/engineering_bay.glb', 'models/mineral_patch.glb', 'models/vespene_geyser.glb',
            'models/reactor.glb', 'models/techlab.glb', 'models/techlab_barracks.glb', 'models/techlab_starport.glb'}
UNKNOWN = set()

used = {os.path.basename(x) for x in subprocess.run("grep -rhoE '[A-Za-z0-9_./-]+\\.glb' src index.html --exclude-dir=credits", shell=True, capture_output=True, text=True).stdout.split()}
groups, unknown, own = {}, [], []
for f in sorted(glob.glob('public/**/*.glb', recursive=True)) + ['public/' + k for k in EXTRA]:
    rel = f[len('public/'):]; ex = OVERRIDES.get(rel) or EXTRA.get(rel) or meta(f)
    isUsed = os.path.basename(f) in used or rel in EXTRA
    if rel in OWN_WORK:
        own.append({'file': rel, 'used': isUsed}); continue
    if rel in UNKNOWN or not ex.get('source'):
        unknown.append({'file': rel, 'used': isUsed}); continue
    m = re.match(r'^(.*?)\s*\((https?://[^)]+)\)\s*$', ex.get('author', ''))
    author, aurl = (m.group(1), m.group(2)) if m else (ex.get('author'), ex.get('authorUrl'))
    lic = re.match(r'^(\S+)', ex.get('license', '')).group(1)
    g = groups.setdefault(ex['source'], {'title': ex.get('title'), 'author': author, 'authorUrl': aurl, 'license': lic, 'source': ex['source'], 'files': [], 'used': False})
    g['files'].append(rel); g['used'] |= isUsed
    if not g['title']: g['title'] = os.path.splitext(os.path.basename(f))[0].replace('_', ' ')
out = {'note': 'Generated by tools/model/credits.py. "used" = referenced by the game code; unused files still ship in public/. Models with license CC-BY-NC-4.0 are non-commercial only.',
       'credits': sorted(groups.values(), key=lambda g: (not g['used'], g['author'].lower(), g['title'] or '')),
       'ownWork': {'author': 'Project owner', 'files': own},
       'unknownAuthor': unknown}
json.dump(out, open('src/credits/modelCredits.json', 'w'), indent=1, ensure_ascii=False)
u = [g for g in out['credits'] if g['used']]
print(len(own), 'own-work files;', len(out['credits']), 'source models,', len(u), 'used;', len(unknown), 'files without author')
from collections import Counter
print(Counter((g['author'], g['license']) for g in u))
